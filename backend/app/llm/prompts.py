DEFAULT_LEVEL = "experienced"


def with_level(system_prompt: str, level: str = DEFAULT_LEVEL) -> str:
    """Вшивает профиль аудитории в системный промпт.

    level сохранён для обратной совместимости API; используется единый
    профиль «Опытный+» (базовый уровень и деление опытный/эксперт убраны).
    """
    return system_prompt + "\n\n" + AUDIENCE_BAN + "\n\n" + LEVEL_PROFILE


